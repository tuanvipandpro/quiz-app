export function translate(language, key, params = {}) {
  const singular = {
    '{count} quiz sets': '{count} quiz set',
    '{count} questions': '{count} question',
    '{count} minutes': '{count} minute',
  };
  let text =
    language === 'vi'
      ? (vi[key] ?? key)
      : params.count === 1 && singular[key]
        ? singular[key]
        : key;
  const questionError = language === 'vi' && key.match(/^Question (\d+): (.+)$/);
  if (questionError) text = `Câu ${questionError[1]}: ${vi[questionError[2]] ?? questionError[2]}`;
  return text.replace(/\{(\w+)\}/g, (match, name) =>
    Object.hasOwn(params, name) ? String(params[name]) : match
  );
}
